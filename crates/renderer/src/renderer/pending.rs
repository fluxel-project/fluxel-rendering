//! Concrete workload owners retained until covering completion.

use super::*;

pub(crate) enum PendingWork<B>
where
    B: ExecutionBackend + ResourceBackend + MappingBackend + ReadbackBackend,
{
    ForwardDeferredCapture {
        _producer: Box<forward::CaptureOitSide<B>>,
        _receiver: Box<crate::residency::DeferredFrame<B>>,
        plan: Arc<crate::graph::ForwardDeferredCapturePlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    ForwardDeferredCaptureSurface {
        _producer: Box<forward::CaptureOitSide<B>>,
        _receiver: Box<crate::residency::DeferredFrame<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<crate::graph::ForwardDeferredCapturePlan<B>>,
    },
    DeferredForwardCapture {
        _producer: Box<crate::residency::DeferredFrame<B>>,
        _composition: Option<Box<deferred::DeferredCaptureComposition<B>>>,
        _receiver: Box<forward::CaptureOitSide<B>>,
        plan: Arc<crate::graph::DeferredForwardCapturePlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    DeferredForwardCaptureSurface {
        _producer: Box<crate::residency::DeferredFrame<B>>,
        _composition: Option<Box<deferred::DeferredCaptureComposition<B>>>,
        _receiver: Box<forward::CaptureOitSide<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<crate::graph::DeferredForwardCapturePlan<B>>,
    },
    DeferredCapture {
        _producer: Box<crate::residency::DeferredFrame<B>>,
        _composition: Option<Box<deferred::DeferredCaptureComposition<B>>>,
        _receiver: Box<crate::residency::DeferredFrame<B>>,
        plan: Arc<crate::graph::DeferredCapturePlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    DeferredCaptureSurface {
        _producer: Box<crate::residency::DeferredFrame<B>>,
        _composition: Option<Box<deferred::DeferredCaptureComposition<B>>>,
        _receiver: Box<crate::residency::DeferredFrame<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<crate::graph::DeferredCapturePlan<B>>,
    },
    Deferred {
        _frame: Box<crate::residency::DeferredFrame<B>>,
        plan: Arc<crate::graph::DeferredPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    CaptureForwardSurface {
        _capture: Box<crate::residency::ForwardFrame<B>>,
        _receiver: Box<crate::residency::ForwardFrame<B>>,
        capture_publication: forward::ForwardPublication,
        receiver_publication: forward::ForwardPublication,
        _composite: SurfaceCompositeOwner<B>,
        /// Unconsumed lease returned by a failed present handoff. It remains
        /// owned until completion/idle proves the preceding scopes are safe.
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<crate::graph::CaptureForwardSurfacePlan<B>>,
    },
    DeferredSurface {
        _frame: Box<crate::residency::DeferredSurfaceFrame<B>>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<crate::graph::DeferredPlan<B>>,
    },
    Forward {
        _frame: Box<crate::residency::ForwardFrame<B>>,
        _oit: Option<Box<forward::OitFrameResources<B>>>,
        /// The HDR offscreen terminal's color conversion pipeline/bindings.
        /// It owns backend objects used by the submitted terminal pass.
        _composite: Option<SurfaceCompositeOwner<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::ForwardPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    ForwardSurface {
        _frame: Box<crate::residency::SurfaceForwardFrame<B>>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::SurfaceForwardPlan<B>>,
    },
    ForwardHdrSurface {
        _frame: Box<crate::residency::ForwardFrame<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::ForwardPlan<B>>,
    },
    ForwardOitSurface {
        _frame: Box<crate::residency::ForwardFrame<B>>,
        _oit: Box<forward::OitFrameResources<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::ForwardPlan<B>>,
    },
    /// One combined Graph submission retaining its producer and receiver.
    CaptureForward {
        _capture: Box<crate::residency::ForwardFrame<B>>,
        _receiver: Box<crate::residency::ForwardFrame<B>>,
        _composite: Option<SurfaceCompositeOwner<B>>,
        capture_publication: forward::ForwardPublication,
        receiver_publication: forward::ForwardPublication,
        plan: Arc<crate::graph::CaptureForwardPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    CaptureOit {
        _capture: Box<crate::residency::ForwardFrame<B>>,
        _receiver: Box<crate::residency::ForwardFrame<B>>,
        _capture_oit: Option<Box<forward::OitFrameResources<B>>>,
        _receiver_oit: Option<Box<forward::OitFrameResources<B>>>,
        capture_publication: forward::ForwardPublication,
        receiver_publication: forward::ForwardPublication,
        /// The HDR offscreen terminal's color conversion pipeline/bindings.
        _composite: Option<SurfaceCompositeOwner<B>>,
        plan: Arc<crate::graph::CaptureOitPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    CaptureOitSurface {
        _capture: Box<crate::residency::ForwardFrame<B>>,
        _receiver: Box<crate::residency::ForwardFrame<B>>,
        _capture_oit: Option<Box<forward::OitFrameResources<B>>>,
        _receiver_oit: Option<Box<forward::OitFrameResources<B>>>,
        capture_publication: forward::ForwardPublication,
        receiver_publication: forward::ForwardPublication,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<crate::graph::CaptureOitPlan<B>>,
    },
    DeferredTransparent {
        _opaque: Box<crate::residency::DeferredFrame<B>>,
        _transparent: Box<crate::residency::ForwardFrame<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::DeferredTransparentPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    DeferredTransparentSurface {
        _opaque: Box<crate::residency::DeferredFrame<B>>,
        _transparent: Box<crate::residency::ForwardFrame<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::DeferredTransparentPlan<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
    },
    DeferredOit {
        _opaque: Box<crate::residency::DeferredFrame<B>>,
        _transparent: Box<crate::residency::ForwardFrame<B>>,
        _oit: Box<forward::OitFrameResources<B>>,
        _composite: SurfaceCompositeOwner<B>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::DeferredOitPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    DeferredOitSurface {
        _opaque: Box<crate::residency::DeferredFrame<B>>,
        _transparent: Box<crate::residency::ForwardFrame<B>>,
        _oit: Box<forward::OitFrameResources<B>>,
        _composite: SurfaceCompositeOwner<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        publication: forward::ForwardPublication,
        plan: Arc<crate::graph::DeferredOitPlan<B>>,
    },
    Copy {
        _buffers: UploadBuffers<B>,
        _frame: CopyFrame,
        plan: Arc<CopyPlan<B>>,
    },
    Raster {
        _buffers: Box<RasterBuffers<B>>,
        _pipeline: RasterPipeline<B>,
        plan: Arc<RasterPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
    SurfaceRaster {
        _buffers: SurfaceRasterBuffers<B>,
        _pipeline: RasterPipeline<B>,
        _present: Option<fluxel_rhi::api::PresentBinding<B>>,
        plan: Arc<SurfaceRasterPlan<B>>,
    },
    Compute {
        _buffers: ComputeBuffers<B>,
        _bindings: ComputeFixtureBindings<B>,
        _pipeline: ComputePipeline<B>,
        plan: Arc<ComputePlan<B>>,
    },
    ReadSetRaster {
        _frame: ReadSetRasterFrame,
        _buffers: Box<ReadSetRasterBuffers<B>>,
        _bindings: ReadSetRasterBindings<B>,
        _pipeline: RasterPipeline<B>,
        plan: Arc<ReadSetRasterPlan<B>>,
        extent: [u32; 2],
        row_pitch: u32,
    },
}
